def pick(v, lang):
    if isinstance(v, dict) and set(v) == {"en","da"}: return v[lang]
    if isinstance(v, dict): return {k: pick(x, lang) for k, x in v.items()}
    if isinstance(v, list): return [pick(x, lang) for x in v]
    return v
